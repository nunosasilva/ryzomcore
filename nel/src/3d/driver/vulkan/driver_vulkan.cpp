/// Monotonic nanoseconds for the optional NLVK_STATS frame breakdown.
static uint64 nowNs()
{
	return (uint64)std::chrono::duration_cast<std::chrono::nanoseconds>(
		std::chrono::steady_clock::now().time_since_epoch()).count();
}

