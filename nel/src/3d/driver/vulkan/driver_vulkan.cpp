bool CDriverVulkan::createPipelineCache()
{
	_PipelineCachePath = CPath::getApplicationDirectory("ryzom") + "vulkan_pipeline_cache.bin";

	vector<uint8> initialData;
	if (pipelineCacheOnDisk())
	{
		FILE *file = nlfopen(_PipelineCachePath, "rb");
		if (file != NULL)
		{
			if (fseek(file, 0, SEEK_END) == 0)
			{
				const long size = ftell(file);
				// A cache larger than this is not worth reading; start fresh.
				if (size > 0 && size <= 64 * 1024 * 1024)
				{
					initialData.resize((size_t)size);
					if (fseek(file, 0, SEEK_SET) == 0 &&
						fread(&initialData[0], 1, initialData.size(), file) != initialData.size())
						initialData.clear();
				}
			}
			fclose(file);
		}
	}

	VkPipelineCacheCreateInfo pcci;
	memset(&pcci, 0, sizeof(pcci));
	pcci.sType = VK_STRUCTURE_TYPE_PIPELINE_CACHE_CREATE_INFO;
	pcci.initialDataSize = initialData.size();
	pcci.pInitialData = initialData.empty() ? NULL : &initialData[0];

	const VkResult result = vkCreatePipelineCache(_Device, &pcci, NULL, &_VkPipelineCache);
	if (result != VK_SUCCESS)
	{
		nlwarning("Vulkan: vkCreatePipelineCache failed (%d %s); pipelines will be compiled without a cache",
			(int)result, vkResultName(result));
		_VkPipelineCache = VK_NULL_HANDLE;
		return false;
	}

	if (initialData.empty())
		nlinfo("Vulkan: pipeline cache: starting empty (%s)",
			pipelineCacheOnDisk() ? _PipelineCachePath.c_str() : "disk persistence disabled");
	else
		nlinfo("Vulkan: pipeline cache: loaded %u KiB from %s",
			(uint)(initialData.size() / 1024), _PipelineCachePath.c_str());
	return true;
}

void CDriverVulkan::savePipelineCache()
{
	if (_VkPipelineCache == VK_NULL_HANDLE || _Device == VK_NULL_HANDLE)
		return;

	size_t size = 0;
	if (vkGetPipelineCacheData(_Device, _VkPipelineCache, &size, NULL) == VK_SUCCESS && size > 0)
	{
		vector<uint8> data(size);
		if (vkGetPipelineCacheData(_Device, _VkPipelineCache, &size, &data[0]) == VK_SUCCESS)
		{
			if (pipelineCacheOnDisk())
			{
				CFile::createDirectoryTree(CFile::getPath(_PipelineCachePath));
				// Write next to the final name and move it into place, so a
				// crash or a second client cannot leave a truncated cache.
				const std::string tmpPath = _PipelineCachePath + ".tmp";
				FILE *file = nlfopen(tmpPath, "wb");
				if (file != NULL)
				{
					const bool ok = fwrite(&data[0], 1, size, file) == size;
					fclose(file);
					// Windows' MoveFile does not replace an existing file.
					CFile::deleteFile(_PipelineCachePath);
					if (ok && CFile::moveFile(_PipelineCachePath, tmpPath))
						nlinfo("Vulkan: pipeline cache: saved %u KiB (%u pipelines) to %s",
							(uint)(size / 1024), (uint)_PipelineCache.size(), _PipelineCachePath.c_str());
					else
						nlwarning("Vulkan: could not write the pipeline cache '%s'", _PipelineCachePath.c_str());
				}
				else
					nlwarning("Vulkan: could not open the pipeline cache '%s' for writing", _PipelineCachePath.c_str());
			}
		}
	}

	vkDestroyPipelineCache(_Device, _VkPipelineCache, NULL);
	_VkPipelineCache = VK_NULL_HANDLE;
}

bool CDriverVulkan::createSwapchain()
{
	VkSurfaceCapabilitiesKHR caps;
	if (!checkVk(vkGetPhysicalDeviceSurfaceCapabilitiesKHR(_PhysicalDevice, _Surface, &caps), "vkGetPhysicalDeviceSurfaceCapabilitiesKHR"))
		return false;

	// X11 reports the drawable size in currentExtent (0xFFFFFFFF means "the
	// surface decides", e.g. Wayland). A minimised window reports 0x0, which
	// vkCreateSwapchainKHR rejects: clamp every extent to the surface's valid
	// range. beginFrame() stops rendering while the window has no size at all,
	// so the clamped 1x1 swapchain is never presented.
	uint32 surfaceWidth = caps.currentExtent.width;
	uint32 surfaceHeight = caps.currentExtent.height;
	if (surfaceWidth == 0xFFFFFFFFu)
	{
		surfaceWidth = _WindowWidth;
		surfaceHeight = _WindowHeight;
	}
	_SwapchainExtent.width = std::max(caps.minImageExtent.width,
		std::min(caps.maxImageExtent.width, std::max(1u, surfaceWidth)));
	_SwapchainExtent.height = std::max(caps.minImageExtent.height,
		std::min(caps.maxImageExtent.height, std::max(1u, surfaceHeight)));

	uint32 formatCount = 0;
	vkGetPhysicalDeviceSurfaceFormatsKHR(_PhysicalDevice, _Surface, &formatCount, NULL);
	vector<VkSurfaceFormatKHR> formats(formatCount);
	vkGetPhysicalDeviceSurfaceFormatsKHR(_PhysicalDevice, _Surface, &formatCount, &formats[0]);
	// The GL3 driver renders into a non-sRGB default framebuffer: shader
	// output is already in display space and goes to the screen unchanged.
	// Prefer the matching UNORM surface here too. An _SRGB swapchain would
	// apply the sRGB encode a second time and make every texture brighter
	// than in the OpenGL client.
	VkSurfaceFormatKHR chosen = formats[0];
	bool chosenUnorm = false;
	for (uint i = 0; i < formats.size(); ++i)
	{
		if (formats[i].format == VK_FORMAT_B8G8R8A8_UNORM)
		{
			chosen = formats[i];
			chosenUnorm = true;
			break;
		}
	}
	if (!chosenUnorm)
	{
		for (uint i = 0; i < formats.size(); ++i)
		{
			if (formats[i].format == VK_FORMAT_B8G8R8A8_SRGB)
			{
				chosen = formats[i];
				nlwarning("Vulkan: surface offers no B8G8R8A8_UNORM; using sRGB swapchain (colours will be brighter than GL3)");
				break;
			}
		}
	}
	_SwapchainFormat = chosen.format;
	if (_SwapchainFormat != VK_FORMAT_B8G8R8A8_UNORM && _SwapchainFormat != VK_FORMAT_B8G8R8A8_SRGB)
		nlwarning("Vulkan: swapchain format %d is not B8G8R8A8; colours and screenshots assume BGRA", (int)_SwapchainFormat);
	nlinfo("Vulkan: swapchain format %d (%s), %u surface format(s) offered",
		(int)_SwapchainFormat,
		_SwapchainFormat == VK_FORMAT_B8G8R8A8_UNORM ? "B8G8R8A8_UNORM" :
		_SwapchainFormat == VK_FORMAT_B8G8R8A8_SRGB ? "B8G8R8A8_SRGB" : "other",
		formatCount);

	uint32 imageCount = caps.minImageCount + 1;
	if (caps.maxImageCount > 0 && imageCount > caps.maxImageCount)
		imageCount = caps.maxImageCount;

	VkSwapchainCreateInfoKHR sci;
	memset(&sci, 0, sizeof(sci));
	sci.sType = VK_STRUCTURE_TYPE_SWAPCHAIN_CREATE_INFO_KHR;
	sci.surface = _Surface;
	sci.minImageCount = imageCount;
	sci.imageFormat = _SwapchainFormat;
	sci.imageColorSpace = chosen.colorSpace;
	sci.imageExtent = _SwapchainExtent;
	sci.imageArrayLayers = 1;
	sci.imageUsage = VK_IMAGE_USAGE_COLOR_ATTACHMENT_BIT | VK_IMAGE_USAGE_TRANSFER_SRC_BIT;
	sci.imageSharingMode = VK_SHARING_MODE_EXCLUSIVE;
	sci.preTransform = caps.currentTransform;
	sci.compositeAlpha = VK_COMPOSITE_ALPHA_OPAQUE_BIT_KHR;
	sci.presentMode = VK_PRESENT_MODE_FIFO_KHR;
	sci.clipped = VK_TRUE;
	sci.oldSwapchain = _Swapchain;
	if (!checkVk(vkCreateSwapchainKHR(_Device, &sci, NULL, &_Swapchain), "vkCreateSwapchainKHR"))
		return false;

	if (sci.oldSwapchain != VK_NULL_HANDLE)
		vkDestroySwapchainKHR(_Device, sci.oldSwapchain, NULL);

	vkGetSwapchainImagesKHR(_Device, _Swapchain, &imageCount, NULL);
	_SwapchainImages.resize(imageCount);
	vkGetSwapchainImagesKHR(_Device, _Swapchain, &imageCount, &_SwapchainImages[0]);

	_SwapchainViews.resize(imageCount);
	for (uint i = 0; i < imageCount; ++i)
	{
		VkImageViewCreateInfo vci;
		memset(&vci, 0, sizeof(vci));
		vci.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
		vci.image = _SwapchainImages[i];
		vci.viewType = VK_IMAGE_VIEW_TYPE_2D;
		vci.format = _SwapchainFormat;
		vci.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
		vci.subresourceRange.levelCount = 1;
		vci.subresourceRange.layerCount = 1;
		if (!checkVk(vkCreateImageView(_Device, &vci, NULL, &_SwapchainViews[i]), "vkCreateImageView(swapchain)"))
			return false;
	}

	// One render-finished semaphore per swapchain image: the presentation engine
	// may still be waiting on the semaphore of the image it is presenting.
	for (uint i = 0; i < _RenderFinished.size(); ++i)
		if (_RenderFinished[i]) vkDestroySemaphore(_Device, _RenderFinished[i], NULL);
	_RenderFinished.resize(imageCount);
	VkSemaphoreCreateInfo semInfo;
	memset(&semInfo, 0, sizeof(semInfo));
	semInfo.sType = VK_STRUCTURE_TYPE_SEMAPHORE_CREATE_INFO;
	for (uint i = 0; i < imageCount; ++i)
	{
		if (!checkVk(vkCreateSemaphore(_Device, &semInfo, NULL, &_RenderFinished[i]), "vkCreateSemaphore(present)"))
			return false;
	}

	nlinfo("Vulkan: swapchain %ux%u, %u images", _SwapchainExtent.width, _SwapchainExtent.height, imageCount);
	// The surface extent is the drawable size (X11) clamped to what the surface
	// accepts: cache it as the window size so getWindowSize() and the next
	// frame's resize check agree with the images. The game loop does not call
	// isActive(), so a window-manager resize is otherwise only noticed through
	// an out-of-date present result.
	_WindowWidth = _SwapchainExtent.width;
	_WindowHeight = _SwapchainExtent.height;
	_SwapchainOutOfDate = false;
	++_SwapchainGeneration;
	return true;
}

bool CDriverVulkan::createRenderPass()
{
	VkAttachmentDescription attachments[2];
	memset(attachments, 0, sizeof(attachments));
	attachments[0].format = _SwapchainFormat;
	attachments[0].samples = VK_SAMPLE_COUNT_1_BIT;
	attachments[0].loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
	attachments[0].storeOp = VK_ATTACHMENT_STORE_OP_STORE;
	attachments[0].stencilLoadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
	attachments[0].stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
	attachments[0].initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
	attachments[0].finalLayout = VK_IMAGE_LAYOUT_PRESENT_SRC_KHR;

	attachments[1].format = _DepthFormat;
	attachments[1].samples = VK_SAMPLE_COUNT_1_BIT;
	attachments[1].loadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
	attachments[1].storeOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
	attachments[1].stencilLoadOp = VK_ATTACHMENT_LOAD_OP_CLEAR;
	attachments[1].stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
	attachments[1].initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
	attachments[1].finalLayout = VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL;

	VkAttachmentReference colorRef;
	colorRef.attachment = 0;
	colorRef.layout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
	VkAttachmentReference depthRef;
	depthRef.attachment = 1;
	depthRef.layout = VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL;

	VkSubpassDescription subpass;
	memset(&subpass, 0, sizeof(subpass));
	subpass.pipelineBindPoint = VK_PIPELINE_BIND_POINT_GRAPHICS;
	subpass.colorAttachmentCount = 1;
	subpass.pColorAttachments = &colorRef;
	subpass.pDepthStencilAttachment = &depthRef;

	VkSubpassDependency dependency;
	memset(&dependency, 0, sizeof(dependency));
	dependency.srcSubpass = VK_SUBPASS_EXTERNAL;
	dependency.dstSubpass = 0;
	dependency.srcStageMask = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT | VK_PIPELINE_STAGE_EARLY_FRAGMENT_TESTS_BIT;
	dependency.dstStageMask = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT | VK_PIPELINE_STAGE_EARLY_FRAGMENT_TESTS_BIT;
	dependency.srcAccessMask = 0;
	dependency.dstAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT | VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT;

	VkRenderPassCreateInfo rpci;
	memset(&rpci, 0, sizeof(rpci));
	rpci.sType = VK_STRUCTURE_TYPE_RENDER_PASS_CREATE_INFO;
	rpci.attachmentCount = 2;
	rpci.pAttachments = attachments;
	rpci.subpassCount = 1;
	rpci.pSubpasses = &subpass;
	rpci.dependencyCount = 1;
	rpci.pDependencies = &dependency;
	if (!checkVk(vkCreateRenderPass(_Device, &rpci, NULL, &_RenderPass), "vkCreateRenderPass"))
		return false;

	// Same attachments, LOAD instead of CLEAR: resumes the main pass in the
	// middle of a frame after an offscreen target was bound. Render-pass
	// compatible with _RenderPass, so both share the cached pipelines.
	attachments[0].loadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
	attachments[0].initialLayout = VK_IMAGE_LAYOUT_PRESENT_SRC_KHR;
	attachments[1].loadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
	attachments[1].stencilLoadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
	attachments[1].initialLayout = VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL;
	if (!checkVk(vkCreateRenderPass(_Device, &rpci, NULL, &_ResumeRenderPass), "vkCreateRenderPass(resume)"))
		return false;

	// Offscreen pass: RGBA8 colour target, same depth format as the window, so
	// the same depth/stencil attachments can be shared by every target of a
	// given size. Both attachments are loaded: the engine clears what it needs.
	attachments[0].format = NL_VK_TEXTURE_FORMAT;
	attachments[0].loadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
	attachments[0].storeOp = VK_ATTACHMENT_STORE_OP_STORE;
	attachments[0].initialLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
	attachments[0].finalLayout = VK_IMAGE_LAYOUT_COLOR_ATTACHMENT_OPTIMAL;
	attachments[0].stencilLoadOp = VK_ATTACHMENT_LOAD_OP_DONT_CARE;
	attachments[0].stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
	attachments[1].format = _DepthFormat;
	attachments[1].loadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
	attachments[1].stencilLoadOp = VK_ATTACHMENT_LOAD_OP_LOAD;
	attachments[1].storeOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
	attachments[1].stencilStoreOp = VK_ATTACHMENT_STORE_OP_DONT_CARE;
	attachments[1].initialLayout = VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL;
	attachments[1].finalLayout = VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL;
	if (!checkVk(vkCreateRenderPass(_Device, &rpci, NULL, &_OffscreenRenderPass), "vkCreateRenderPass(offscreen)"))
		return false;

	return true;
}

VkFormat CDriverVulkan::findDepthFormat() const
{
	const VkFormat candidates[] = {
		VK_FORMAT_D32_SFLOAT,
		VK_FORMAT_D32_SFLOAT_S8_UINT,
		VK_FORMAT_D24_UNORM_S8_UINT,
		VK_FORMAT_D16_UNORM,
	};
	for (uint i = 0; i < sizeof(candidates) / sizeof(candidates[0]); ++i)
	{
		VkFormatProperties props;
		vkGetPhysicalDeviceFormatProperties(_PhysicalDevice, candidates[i], &props);
		if (props.optimalTilingFeatures & VK_FORMAT_FEATURE_DEPTH_STENCIL_ATTACHMENT_BIT)
			return candidates[i];
	}
	return VK_FORMAT_UNDEFINED;
}

bool CDriverVulkan::createDepthResources()
{
	destroyDepthResources();
	const uint imageCount = (uint)_SwapchainImages.size();
	_DepthImages.assign(imageCount, VK_NULL_HANDLE);
	_DepthMemories.assign(imageCount, VK_NULL_HANDLE);
	_DepthViews.assign(imageCount, VK_NULL_HANDLE);

	for (uint i = 0; i < imageCount; ++i)
	{
		VkImageCreateInfo ici;
		memset(&ici, 0, sizeof(ici));
		ici.sType = VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO;
		ici.imageType = VK_IMAGE_TYPE_2D;
		ici.extent.width = _SwapchainExtent.width;
		ici.extent.height = _SwapchainExtent.height;
		ici.extent.depth = 1;
		ici.mipLevels = 1;
		ici.arrayLayers = 1;
		ici.format = _DepthFormat;
		ici.tiling = VK_IMAGE_TILING_OPTIMAL;
		ici.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
		ici.usage = VK_IMAGE_USAGE_DEPTH_STENCIL_ATTACHMENT_BIT;
		ici.samples = VK_SAMPLE_COUNT_1_BIT;
		ici.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
		if (!checkVk(vkCreateImage(_Device, &ici, NULL, &_DepthImages[i]), "vkCreateImage(depth)"))
			return false;

		VkMemoryRequirements req;
		vkGetImageMemoryRequirements(_Device, _DepthImages[i], &req);
		VkMemoryAllocateInfo mai;
		memset(&mai, 0, sizeof(mai));
		mai.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
		mai.allocationSize = req.size;
		mai.memoryTypeIndex = findMemoryType(req.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
		if (!checkVk(vkAllocateMemory(_Device, &mai, NULL, &_DepthMemories[i]), "vkAllocateMemory(depth)"))
			return false;
		if (!checkVk(vkBindImageMemory(_Device, _DepthImages[i], _DepthMemories[i], 0), "vkBindImageMemory(depth)"))
			return false;

		VkImageViewCreateInfo vci;
		memset(&vci, 0, sizeof(vci));
		vci.sType = VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO;
		vci.image = _DepthImages[i];
		vci.viewType = VK_IMAGE_VIEW_TYPE_2D;
		vci.format = _DepthFormat;
		vci.subresourceRange.aspectMask = VK_IMAGE_ASPECT_DEPTH_BIT;
		if (_DepthFormat == VK_FORMAT_D24_UNORM_S8_UINT || _DepthFormat == VK_FORMAT_D32_SFLOAT_S8_UINT)
			vci.subresourceRange.aspectMask |= VK_IMAGE_ASPECT_STENCIL_BIT;
		vci.subresourceRange.levelCount = 1;
		vci.subresourceRange.layerCount = 1;
		if (!checkVk(vkCreateImageView(_Device, &vci, NULL, &_DepthViews[i]), "vkCreateImageView(depth)"))
			return false;
	}

	return true;
}

void CDriverVulkan::destroyDepthResources()
{
	for (uint i = 0; i < _DepthViews.size(); ++i)
		if (_DepthViews[i]) vkDestroyImageView(_Device, _DepthViews[i], NULL);
	for (uint i = 0; i < _DepthImages.size(); ++i)
		if (_DepthImages[i]) vkDestroyImage(_Device, _DepthImages[i], NULL);
	for (uint i = 0; i < _DepthMemories.size(); ++i)
		if (_DepthMemories[i]) vkFreeMemory(_Device, _DepthMemories[i], NULL);
	_DepthViews.clear();
	_DepthImages.clear();
	_DepthMemories.clear();
}

bool CDriverVulkan::createFramebuffers()
{
	_Framebuffers.resize(_SwapchainViews.size());
	for (uint i = 0; i < _SwapchainViews.size(); ++i)
	{
		VkImageView views[2] = { _SwapchainViews[i], _DepthViews[i] };
		VkFramebufferCreateInfo fci;
		memset(&fci, 0, sizeof(fci));
		fci.sType = VK_STRUCTURE_TYPE_FRAMEBUFFER_CREATE_INFO;
		fci.renderPass = _RenderPass;
		fci.attachmentCount = 2;
		fci.pAttachments = views;
		fci.width = _SwapchainExtent.width;
		fci.height = _SwapchainExtent.height;
		fci.layers = 1;
		if (!checkVk(vkCreateFramebuffer(_Device, &fci, NULL, &_Framebuffers[i]), "vkCreateFramebuffer"))
			return false;
	}
	return true;
}

bool CDriverVulkan::createCommands()
{
	VkCommandPoolCreateInfo pci;
	memset(&pci, 0, sizeof(pci));
	pci.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO;
	pci.queueFamilyIndex = _GraphicsFamily;
	pci.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT;
	if (!checkVk(vkCreateCommandPool(_Device, &pci, NULL, &_CommandPool), "vkCreateCommandPool"))
		return false;

	_CommandBuffers.resize(4);
	VkCommandBufferAllocateInfo cbi;
	memset(&cbi, 0, sizeof(cbi));
	cbi.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
	cbi.commandPool = _CommandPool;
	cbi.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
	cbi.commandBufferCount = 4;
	if (!checkVk(vkAllocateCommandBuffers(_Device, &cbi, &_CommandBuffers[0]), "vkAllocateCommandBuffers"))
		return false;
	// 0/1: the two frames in flight. 2/3: the texture upload command buffer of
	// each frame, submitted ahead of it.
	_UploadCommandBuffers[0] = _CommandBuffers[2];
	_UploadCommandBuffers[1] = _CommandBuffers[3];
	return true;
}

bool CDriverVulkan::createSyncObjects()
{
	_Fences.resize(2);
	_ImageAvailable.resize(2);
	VkFenceCreateInfo fci;
	memset(&fci, 0, sizeof(fci));
	fci.sType = VK_STRUCTURE_TYPE_FENCE_CREATE_INFO;
	fci.flags = VK_FENCE_CREATE_SIGNALED_BIT;
	VkSemaphoreCreateInfo sci;
	memset(&sci, 0, sizeof(sci));
	sci.sType = VK_STRUCTURE_TYPE_SEMAPHORE_CREATE_INFO;
	for (uint i = 0; i < 2; ++i)
	{
		if (!checkVk(vkCreateFence(_Device, &fci, NULL, &_Fences[i]), "vkCreateFence"))
			return false;
		if (!checkVk(vkCreateSemaphore(_Device, &sci, NULL, &_ImageAvailable[i]), "vkCreateSemaphore"))
			return false;
	}
	// Uploads are submitted with the frame command buffer (see swapBuffers()),
	// so they need no fence or semaphore of their own.
	return true;
}

bool CDriverVulkan::createOcclusionPools()
{
	VkQueryPoolCreateInfo qpci;
	memset(&qpci, 0, sizeof(qpci));
	qpci.sType = VK_STRUCTURE_TYPE_QUERY_POOL_CREATE_INFO;
	qpci.queryType = VK_QUERY_TYPE_OCCLUSION;
	qpci.queryCount = NL_VK_OCCLUSION_SLOTS;
	for (uint i = 0; i < 2; ++i)
	{
		const VkResult result = vkCreateQueryPool(_Device, &qpci, NULL, &_OcclusionPools[i]);
		if (result != VK_SUCCESS)
		{
			nlwarning("Vulkan: vkCreateQueryPool(occlusion, %u) failed (%d %s); flares disabled",
				NL_VK_OCCLUSION_SLOTS, (int)result, vkResultName(result));
			if (_OcclusionPools[0]) { vkDestroyQueryPool(_Device, _OcclusionPools[0], NULL); _OcclusionPools[0] = VK_NULL_HANDLE; }
			return false;
		}
	}
	nlinfo("Vulkan: occlusion queries enabled (%u slots per frame, precise counts %s)",
		NL_VK_OCCLUSION_SLOTS, _OcclusionPrecise ? "yes" : "no");
	return true;
}

void CDriverVulkan::destroySwapchain()
{
	if (!_Device)
		return;
	vkDeviceWaitIdle(_Device);
	for (uint i = 0; i < _Framebuffers.size(); ++i)
		if (_Framebuffers[i]) vkDestroyFramebuffer(_Device, _Framebuffers[i], NULL);
	_Framebuffers.clear();
	for (uint i = 0; i < _SwapchainViews.size(); ++i)
		if (_SwapchainViews[i]) vkDestroyImageView(_Device, _SwapchainViews[i], NULL);
	_SwapchainViews.clear();
	_SwapchainImages.clear();
	destroyDepthResources();
	// The render pass only depends on the attachment formats, which do not change
	// with the swapchain size: keep it (and therefore every cached pipeline).
	if (_Swapchain) { vkDestroySwapchainKHR(_Device, _Swapchain, NULL); _Swapchain = VK_NULL_HANDLE; }
}

bool CDriverVulkan::initVulkan()
{
	VkApplicationInfo app;
	memset(&app, 0, sizeof(app));
	app.sType = VK_STRUCTURE_TYPE_APPLICATION_INFO;
	app.pApplicationName = "Ryzom";
	app.applicationVersion = VK_MAKE_VERSION(1, 0, 0);
	app.pEngineName = "NeL";
	app.engineVersion = VK_MAKE_VERSION(1, 0, 0);
	app.apiVersion = VK_API_VERSION_1_1;

	const char *extensions[] = {
		VK_KHR_SURFACE_EXTENSION_NAME,
		VK_KHR_XLIB_SURFACE_EXTENSION_NAME,
	};

	bool validation = getenv("NLVK_VALIDATION") != NULL;

	const char *extensionsWithDebug[] = {
		VK_KHR_SURFACE_EXTENSION_NAME,
		VK_KHR_XLIB_SURFACE_EXTENSION_NAME,
		VK_EXT_DEBUG_UTILS_EXTENSION_NAME,
	};

	VkInstanceCreateInfo ici;
	memset(&ici, 0, sizeof(ici));
	ici.sType = VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO;
	ici.pApplicationInfo = &app;
	ici.enabledExtensionCount = validation ? 3 : 2;
	ici.ppEnabledExtensionNames = validation ? extensionsWithDebug : extensions;
	if (validation)
	{
		ici.enabledLayerCount = 1;
		ici.ppEnabledLayerNames = s_ValidationLayers;
	}
	if (!checkVk(vkCreateInstance(&ici, NULL, &_Instance), "vkCreateInstance"))
		return false;

	if (validation)
	{
		VkDebugUtilsMessengerCreateInfoEXT dmci;
		memset(&dmci, 0, sizeof(dmci));
		dmci.sType = VK_STRUCTURE_TYPE_DEBUG_UTILS_MESSENGER_CREATE_INFO_EXT;
		dmci.messageSeverity = VK_DEBUG_UTILS_MESSAGE_SEVERITY_WARNING_BIT_EXT | VK_DEBUG_UTILS_MESSAGE_SEVERITY_ERROR_BIT_EXT;
		dmci.messageType = VK_DEBUG_UTILS_MESSAGE_TYPE_GENERAL_BIT_EXT | VK_DEBUG_UTILS_MESSAGE_TYPE_VALIDATION_BIT_EXT | VK_DEBUG_UTILS_MESSAGE_TYPE_PERFORMANCE_BIT_EXT;
		dmci.pfnUserCallback = vulkanDebugCallback;
		PFN_vkCreateDebugUtilsMessengerEXT createMessenger =
			(PFN_vkCreateDebugUtilsMessengerEXT)vkGetInstanceProcAddr(_Instance, "vkCreateDebugUtilsMessengerEXT");
		if (createMessenger)
			createMessenger(_Instance, &dmci, NULL, &_DebugMessenger);
	}

	if (!createSurface())
		return false;
	if (!pickPhysicalDevice())
		return false;
	if (!createLogicalDevice())
		return false;
	// Not fatal: without it vkCreateGraphicsPipelines compiles every state
	// combination again, which is the main cost of a zone load.
	createPipelineCache();
	_DepthFormat = findDepthFormat();
	if (_DepthFormat == VK_FORMAT_UNDEFINED)
	{
		nlwarning("Vulkan: no supported depth format");
		return false;
	}
	if (!createSwapchain())
		return false;
	if (!createRenderPass())
		return false;
	if (!createDepthResources())
		return false;
	if (!createFramebuffers())
		return false;
	if (!createCommands())
		return false;
	if (!createSyncObjects())
		return false;
	// Occlusion queries for the flares. Not fatal: without the pools the
	// driver reports no support and the engine skips flares, as before.
	createOcclusionPools();

	// NLVK_STATS: one GPU timestamp pair per frame slot, written around the
	// frame command buffer. Timestamps need support from the queue family.
	if (_StatsEnabled)
	{
		uint32 qcount = 0;
		vkGetPhysicalDeviceQueueFamilyProperties(_PhysicalDevice, &qcount, NULL);
		vector<VkQueueFamilyProperties> queues(qcount);
		vkGetPhysicalDeviceQueueFamilyProperties(_PhysicalDevice, &qcount, &queues[0]);
		const bool hasTimestamps =
			_GraphicsFamily < queues.size() && queues[_GraphicsFamily].timestampValidBits > 0;
		VkQueryPoolCreateInfo qpci;
		memset(&qpci, 0, sizeof(qpci));
		qpci.sType = VK_STRUCTURE_TYPE_QUERY_POOL_CREATE_INFO;
		qpci.queryType = VK_QUERY_TYPE_TIMESTAMP;
		qpci.queryCount = 4;
		if (hasTimestamps && vkCreateQueryPool(_Device, &qpci, NULL, &_GpuTimeQuery) == VK_SUCCESS)
		{
			_GpuTimeEnabled = true;
			_GpuTimePeriod = _DeviceProps.limits.timestampPeriod;
			if (_GpuTimePeriod <= 0.0)
				_GpuTimePeriod = 1.0;
		}
	}

	// Put every depth image in the layout the render pass expects, once.
	if (!_DepthImages.empty())
	{
		VkCommandBuffer cmd = _CommandBuffers[0];
		VkCommandBufferBeginInfo bi;
		memset(&bi, 0, sizeof(bi));
		bi.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
		bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
		vkBeginCommandBuffer(cmd, &bi);
		std::vector<VkImageMemoryBarrier> barriers(_DepthImages.size());
		for (uint i = 0; i < _DepthImages.size(); ++i)
		{
			VkImageMemoryBarrier &barrier = barriers[i];
			memset(&barrier, 0, sizeof(barrier));
			barrier.sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER;
			barrier.oldLayout = VK_IMAGE_LAYOUT_UNDEFINED;
			barrier.newLayout = VK_IMAGE_LAYOUT_DEPTH_STENCIL_ATTACHMENT_OPTIMAL;
			barrier.srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
			barrier.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
			barrier.image = _DepthImages[i];
			barrier.subresourceRange.aspectMask = VK_IMAGE_ASPECT_DEPTH_BIT;
			barrier.subresourceRange.levelCount = 1;
			barrier.subresourceRange.layerCount = 1;
			barrier.dstAccessMask = VK_ACCESS_DEPTH_STENCIL_ATTACHMENT_WRITE_BIT;
		}
		vkCmdPipelineBarrier(cmd, VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, VK_PIPELINE_STAGE_EARLY_FRAGMENT_TESTS_BIT,
			0, 0, NULL, 0, NULL, (uint32)barriers.size(), &barriers[0]);
		vkEndCommandBuffer(cmd);
		VkSubmitInfo si;
		memset(&si, 0, sizeof(si));
		si.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
		si.commandBufferCount = 1;
		si.pCommandBuffers = &cmd;
		vkQueueSubmit(_GraphicsQueue, 1, &si, VK_NULL_HANDLE);
		vkQueueWaitIdle(_GraphicsQueue);
	}

	// Pipeline layout: 4 texture stages, one push constant block.
	{
		VkDescriptorSetLayoutBinding bindings[5];
		memset(bindings, 0, sizeof(bindings));
		for (uint i = 0; i < 4; ++i)
		{
			bindings[i].binding = i;
			bindings[i].descriptorType = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
			bindings[i].descriptorCount = 1;
			bindings[i].stageFlags = VK_SHADER_STAGE_FRAGMENT_BIT;
		}
		bindings[4].binding = 4;
		bindings[4].descriptorType = VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER;
		bindings[4].descriptorCount = 1;
		bindings[4].stageFlags = VK_SHADER_STAGE_VERTEX_BIT | VK_SHADER_STAGE_FRAGMENT_BIT;
		VkDescriptorSetLayoutCreateInfo dslci;
		memset(&dslci, 0, sizeof(dslci));
		dslci.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO;
		dslci.bindingCount = 5;
		dslci.pBindings = bindings;
		if (!checkVk(vkCreateDescriptorSetLayout(_Device, &dslci, NULL, &_DescriptorSetLayout), "vkCreateDescriptorSetLayout"))
			return false;

		for (uint i = 0; i < 2; ++i)
			if (!createDescriptorPool(i, NL_VK_DESCRIPTOR_POOL_SETS))
				return false;

		VkPipelineLayoutCreateInfo plci;
		memset(&plci, 0, sizeof(plci));
		plci.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO;
		plci.setLayoutCount = 1;
		plci.pSetLayouts = &_DescriptorSetLayout;
		if (!checkVk(vkCreatePipelineLayout(_Device, &plci, NULL, &_PipelineLayout), "vkCreatePipelineLayout"))
			return false;
	}

	// Uniform ring: per-draw uniform slots, host visible, reset each frame.
	// The mega path writes camera, object and material blocks per draw, and a
	// user vertex program adds its own block. Each frame uses its own half, so
	// a frame that is still executing never sees the next frame's blocks; the
	// ring starts small and doubles when a dense frame needs more room.
	_UniformRingSize = 4 * 1024 * 1024;
	{
		VkBufferCreateInfo bci;
		memset(&bci, 0, sizeof(bci));
		bci.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
		bci.size = _UniformRingSize;
		bci.usage = VK_BUFFER_USAGE_UNIFORM_BUFFER_BIT;
		bci.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
		if (!checkVk(vkCreateBuffer(_Device, &bci, NULL, &_UniformRing), "vkCreateBuffer(uniform ring)"))
			return false;
		VkMemoryRequirements req;
		vkGetBufferMemoryRequirements(_Device, _UniformRing, &req);
		VkMemoryAllocateInfo mai;
		memset(&mai, 0, sizeof(mai));
		mai.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
		mai.allocationSize = req.size;
		mai.memoryTypeIndex = findMemoryType(req.memoryTypeBits,
			VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
		if (!checkVk(vkAllocateMemory(_Device, &mai, NULL, &_UniformRingMemory), "vkAllocateMemory(uniform ring)"))
			return false;
		vkBindBufferMemory(_Device, _UniformRing, _UniformRingMemory, 0);
		vkMapMemory(_Device, _UniformRingMemory, 0, VK_WHOLE_SIZE, 0, &_UniformRingMapped);
		_UniformRingHalf = _UniformRingSize / 2;
		_UniformRingFrameBase = 0;
		_UniformRingOffset = 0;
	}

	if (!initMega())
	{
		nlwarning("Vulkan: mega shader resources unavailable, keeping the simple shader path");
		_MegaEnabled = false;
		_MegaResourcesReady = false;
	}

	return true;
}

void CDriverVulkan::shutdownVulkan()
{
	// No frame may be recorded or presented from here on. release() sets this
	// before calling us; the destructor path may run without it.
	_ShuttingDown = true;

	if (_Device)
		vkDeviceWaitIdle(_Device);

	if (_Device)
	{
		for (uint i = 0; i < _PendingTextureDestroy.size(); ++i)
		{
			CTextureVulkan tex = _PendingTextureDestroy[i].second;
			// Render targets own a framebuffer as well as the image and view.
			if (tex.Framebuffer) vkDestroyFramebuffer(_Device, tex.Framebuffer, NULL);
			if (tex.Sampler) vkDestroySampler(_Device, tex.Sampler, NULL);
			if (tex.View) vkDestroyImageView(_Device, tex.View, NULL);
			if (tex.Image) vkDestroyImage(_Device, tex.Image, NULL);
			if (tex.Memory) vkFreeMemory(_Device, tex.Memory, NULL);
		}
		for (uint i = 0; i < _PendingBufferDestroy.size(); ++i)
		{
			vkDestroyBuffer(_Device, _PendingBufferDestroy[i].second.first, NULL);
			if (_PendingBufferDestroy[i].second.second)
				vkFreeMemory(_Device, _PendingBufferDestroy[i].second.second, NULL);
		}
		_PendingTextureDestroy.clear();
		_PendingBufferDestroy.clear();
		_PendingTextureCopies.clear();
	}

	// Destroy the window system objects first: the swapchain must go before the
	// surface, and the presentation semaphores (_RenderFinished) are only free
	// once the swapchain that waits on them is gone.
	destroySwapchain();

	for (uint i = 0; i < _Fences.size(); ++i)
		if (_Fences[i]) vkDestroyFence(_Device, _Fences[i], NULL);
	for (uint i = 0; i < _ImageAvailable.size(); ++i)
		if (_ImageAvailable[i]) vkDestroySemaphore(_Device, _ImageAvailable[i], NULL);
	for (uint i = 0; i < _RenderFinished.size(); ++i)
		if (_RenderFinished[i]) vkDestroySemaphore(_Device, _RenderFinished[i], NULL);
	_Fences.clear();
	_ImageAvailable.clear();
	_RenderFinished.clear();

	if (_CommandPool)
	{
		vkDestroyCommandPool(_Device, _CommandPool, NULL);
		_CommandPool = VK_NULL_HANDLE;
		_CommandBuffers.clear();
	}

	if (_Device)
	{
		// Textures that still have a driver object (whichever ones are left
		// after IDriver::release()) are retired through _PendingTextureDestroy
		// and freed above; nothing else holds a VkImage here.
		_TextureUsed.clear();
		_AllocatedTextureMemory = 0;
		CTextureVulkan &white = _WhiteTexture;
		if (white.Sampler) vkDestroySampler(_Device, white.Sampler, NULL);
		if (white.View) vkDestroyImageView(_Device, white.View, NULL);
		if (white.Image) vkDestroyImage(_Device, white.Image, NULL);
		if (white.Memory) vkFreeMemory(_Device, white.Memory, NULL);
		CTextureVulkan &black = _BlackTexture;
		if (black.Sampler) vkDestroySampler(_Device, black.Sampler, NULL);
		if (black.View) vkDestroyImageView(_Device, black.View, NULL);
		if (black.Image) vkDestroyImage(_Device, black.Image, NULL);
		if (black.Memory) vkFreeMemory(_Device, black.Memory, NULL);

		// Pipelines and layouts.
		for (map<CPipelineKey, CPipelineVulkan>::iterator it = _PipelineCache.begin(); it != _PipelineCache.end(); ++it)
			if (it->second.Pipeline) vkDestroyPipeline(_Device, it->second.Pipeline, NULL);
		_PipelineCache.clear();
		if (_TestPipeline) { vkDestroyPipeline(_Device, _TestPipeline, NULL); _TestPipeline = VK_NULL_HANDLE; }
		// All pipelines are gone: the cache can be written and destroyed.
		savePipelineCache();
		if (_PipelineLayout) { vkDestroyPipelineLayout(_Device, _PipelineLayout, NULL); _PipelineLayout = VK_NULL_HANDLE; }
		if (_DescriptorSetLayout) { vkDestroyDescriptorSetLayout(_Device, _DescriptorSetLayout, NULL); _DescriptorSetLayout = VK_NULL_HANDLE; }
		for (uint i = 0; i < 2; ++i)
		{
			for (size_t pool = 0; pool < _DescriptorPools[i].size(); ++pool)
				vkDestroyDescriptorPool(_Device, _DescriptorPools[i][pool], NULL);
			_DescriptorPools[i].clear();
		}
		if (_GpuTimeQuery) { vkDestroyQueryPool(_Device, _GpuTimeQuery, NULL); _GpuTimeQuery = VK_NULL_HANDLE; }
		for (uint i = 0; i < 2; ++i)
		{
			if (_OcclusionPools[i]) { vkDestroyQueryPool(_Device, _OcclusionPools[i], NULL); _OcclusionPools[i] = VK_NULL_HANDLE; }
			_OcclusionFrameQueries[i].clear();
		}

		// Shaders.
		for (map<uint32, VkShaderModule>::iterator it = _VertexShaderVariants.begin(); it != _VertexShaderVariants.end(); ++it)
			vkDestroyShaderModule(_Device, it->second, NULL);
		_VertexShaderVariants.clear();
		if (_FragmentShader) { vkDestroyShaderModule(_Device, _FragmentShader, NULL); _FragmentShader = VK_NULL_HANDLE; }
		shutdownMega();

		// Ring and debug buffers.
		if (_UniformRing) { vkDestroyBuffer(_Device, _UniformRing, NULL); _UniformRing = VK_NULL_HANDLE; }
		if (_UniformRingMemory) { vkFreeMemory(_Device, _UniformRingMemory, NULL); _UniformRingMemory = VK_NULL_HANDLE; }
		if (_IndexRing) { vkDestroyBuffer(_Device, _IndexRing, NULL); _IndexRing = VK_NULL_HANDLE; }
		if (_IndexRingMemory) { vkFreeMemory(_Device, _IndexRingMemory, NULL); _IndexRingMemory = VK_NULL_HANDLE; }
		if (_VertexRing) { vkDestroyBuffer(_Device, _VertexRing, NULL); _VertexRing = VK_NULL_HANDLE; }
		if (_VertexRingMemory) { vkFreeMemory(_Device, _VertexRingMemory, NULL); _VertexRingMemory = VK_NULL_HANDLE; }
		if (_StagingRing) { vkDestroyBuffer(_Device, _StagingRing, NULL); _StagingRing = VK_NULL_HANDLE; }
		if (_StagingRingMemory) { vkFreeMemory(_Device, _StagingRingMemory, NULL); _StagingRingMemory = VK_NULL_HANDLE; }
		if (_ScreenshotBuffer) { vkDestroyBuffer(_Device, _ScreenshotBuffer, NULL); _ScreenshotBuffer = VK_NULL_HANDLE; }
		if (_ScreenshotMemory) { vkFreeMemory(_Device, _ScreenshotMemory, NULL); _ScreenshotMemory = VK_NULL_HANDLE; }

		// The render passes are kept for the lifetime of the device.
		if (_OffscreenRenderPass) { vkDestroyRenderPass(_Device, _OffscreenRenderPass, NULL); _OffscreenRenderPass = VK_NULL_HANDLE; }
		if (_ResumeRenderPass) { vkDestroyRenderPass(_Device, _ResumeRenderPass, NULL); _ResumeRenderPass = VK_NULL_HANDLE; }
		if (_RenderPass) { vkDestroyRenderPass(_Device, _RenderPass, NULL); _RenderPass = VK_NULL_HANDLE; }
		destroyDepthTargets();

		vkDestroyDevice(_Device, NULL);
		_Device = VK_NULL_HANDLE;
	}
	if (_Surface && _Instance)
	{
		vkDestroySurfaceKHR(_Instance, _Surface, NULL);
		_Surface = VK_NULL_HANDLE;
	}
	if (_Instance)
	{
		if (_DebugMessenger)
		{
			PFN_vkDestroyDebugUtilsMessengerEXT destroyMessenger =
				(PFN_vkDestroyDebugUtilsMessengerEXT)vkGetInstanceProcAddr(_Instance, "vkDestroyDebugUtilsMessengerEXT");
			if (destroyMessenger)
				destroyMessenger(_Instance, _DebugMessenger, NULL);
			_DebugMessenger = VK_NULL_HANDLE;
		}
		vkDestroyInstance(_Instance, NULL);
		_Instance = VK_NULL_HANDLE;
	}

	// The window and the display connection are ours. The WM may already have
	// destroyed the window (or the surface never got created), so X errors are
	// ignored here instead of being turned into a process exit by Xlib.
#if defined(NL_OS_UNIX) && !defined(NL_OS_MAC)
	releaseCursors();
	_EventEmitter.closeIM();
#endif
	if (_Display)
	{
		XErrorHandler oldHandler = XSetErrorHandler(ignoreXError);
		if (_XWindow && _OwnWindow)
		{
			XDestroyWindow(_Display, _XWindow);
			XSync(_Display, False);
		}
		XSetErrorHandler(oldHandler);
		_XWindow = 0;
		XCloseDisplay(_Display);
		_Display = NULL;
	}
}

uint32 CDriverVulkan::findMemoryType(uint32 typeBits, VkMemoryPropertyFlags props) const
{
	VkPhysicalDeviceMemoryProperties mp;
	vkGetPhysicalDeviceMemoryProperties(_PhysicalDevice, &mp);
	for (uint32 i = 0; i < mp.memoryTypeCount; ++i)
		if ((typeBits & (1u << i)) && (mp.memoryTypes[i].propertyFlags & props) == props)
			return i;
	nlwarning("Vulkan: no memory type for properties 0x%x", props);
	return 0;
}

