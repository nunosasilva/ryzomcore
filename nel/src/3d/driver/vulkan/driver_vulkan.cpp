bool CDriverVulkan::setDisplay(nlWindow wnd, const GfxMode &mode, bool show, bool resizeable)
{
	if (_Display)
	{
		nlwarning("Vulkan: setDisplay called twice");
		return true;
	}

	_CurrentMode = mode;
	_Display = XOpenDisplay(NULL);
	if (!_Display)
	{
		nlwarning("Vulkan: cannot open X display");
		return false;
	}
	XSetErrorHandler(logXError);

	_WindowWidth = mode.Width ? mode.Width : 1280;
	_WindowHeight = mode.Height ? mode.Height : 800;

	if (wnd == EmptyWindow)
	{
		_XWindow = XCreateSimpleWindow(_Display, DefaultRootWindow(_Display), 0, 0,
			_WindowWidth, _WindowHeight, 0, 0, 0);
		_OwnWindow = true;
	}
	else
	{
		_XWindow = (Window)wnd;
		_OwnWindow = false;
	}

	XSelectInput(_Display, _XWindow, KeyPressMask | KeyReleaseMask | ButtonPressMask | ButtonReleaseMask |
		PointerMotionMask | StructureNotifyMask | FocusChangeMask | ExposureMask | EnterWindowMask | LeaveWindowMask);
	_WmDeleteMessage = XInternAtom(_Display, "WM_DELETE_WINDOW", False);
	XSetWMProtocols(_Display, _XWindow, &_WmDeleteMessage, 1);
	XStoreName(_Display, _XWindow, "Ryzom");
	XMapWindow(_Display, _XWindow);
	XFlush(_Display);
	_WindowVisible = show;

#if defined(NL_OS_UNIX) && !defined(NL_OS_MAC)
	_EventEmitter.init(_Display, _XWindow, NULL);
#endif

	createCursors();

	if (!initVulkan())
	{
		nlwarning("Vulkan: initVulkan failed");
		return false;
	}
	return true;
}

bool CDriverVulkan::setMode(const GfxMode &mode)
{
	_CurrentMode = mode;
	if (mode.Width && mode.Height && (mode.Width != _SwapchainExtent.width || mode.Height != _SwapchainExtent.height))
	{
		_WindowWidth = mode.Width;
		_WindowHeight = mode.Height;
		XResizeWindow(_Display, _XWindow, _WindowWidth, _WindowHeight);
		// Wait for the server to apply the new geometry: beginFrame() reads the
		// surface extent when it recreates the swapchain at the next frame.
		XSync(_Display, False);
		// beginFrame() replaces the swapchain at the start of the next frame.
		// Recreating it here could happen in the middle of one, after its fence
		// was reset for a submission that the recreation would throw away.
		_SwapchainOutOfDate = true;
	}
	return true;
}

bool CDriverVulkan::recreateSwapchain(const char *reason)
{
	// Nothing to recreate once the driver is shutting down, and nothing to
	// recreate it on once the swapchain is gone for good.
	if (_ShuttingDown || _SwapchainLost || !_Device || !_Surface)
		return false;
	if (!windowAlive())
	{
		// The WM destroyed the window. Asking the surface for its capabilities
		// would only log VK_ERROR_SURFACE_LOST_KHR; stop presenting instead.
		_SwapchainLost = true;
		nlwarning("Vulkan: window destroyed (%s); rendering stopped", reason);
		return false;
	}
	if (!windowHasSize())
	{
		// Minimised, or a window-manager resize passing through 0x0: there is
		// no drawable to create a swapchain for. Keep the current one and let
		// beginFrame() skip the frames until the window has a size again.
		if (_PresentLog)
			nlinfo("Vulkan present: swapchain recreation deferred, window has no size (%s)", reason);
		_SwapchainOutOfDate = true;
		return false;
	}
	if (_FrameOpen)
	{
		// Destroying the swapchain now would pull the images out from under the
		// frame that is being recorded, and that frame has already reset its
		// fence for a submission this would skip: the next beginFrame() would
		// then wait for it forever. Retry at the next frame boundary instead.
		nlwarning("Vulkan: swapchain recreation requested while a frame is recorded (%s); deferred", reason);
		_SwapchainOutOfDate = true;
		return false;
	}
	if (_PresentLog)
		nlinfo("Vulkan present: recreating swapchain (generation %u): %s", _SwapchainGeneration, reason);
	_SwapchainOutOfDate = false;
	destroySwapchain();
	if (!createSwapchain())
	{
		// The surface is gone (window destroyed). There is no way back without
		// a new window: stop presenting instead of calling into a null
		// swapchain every frame.
		_SwapchainLost = true;
		nlwarning("Vulkan: swapchain recreation failed (%s); rendering stopped", reason);
		return false;
	}
	// A half-recreated swapchain cannot be rendered into (missing depth
	// attachment or framebuffer); stop rather than use null handles.
	if (!createDepthResources() || !createFramebuffers())
	{
		_SwapchainLost = true;
		nlwarning("Vulkan: swapchain attachments could not be created (%s); rendering stopped", reason);
		return false;
	}
	return true;
}

