bool CDriverVulkan::createSurface()
{
	VkXlibSurfaceCreateInfoKHR sci;
	memset(&sci, 0, sizeof(sci));
	sci.sType = VK_STRUCTURE_TYPE_XLIB_SURFACE_CREATE_INFO_KHR;
	sci.dpy = _Display;
	sci.window = _XWindow;
	if (!checkVk(vkCreateXlibSurfaceKHR(_Instance, &sci, NULL, &_Surface), "vkCreateXlibSurfaceKHR"))
		return false;
	return true;
}

bool CDriverVulkan::pickPhysicalDevice()
{
	uint32 count = 0;
	if (!checkVk(vkEnumeratePhysicalDevices(_Instance, &count, NULL), "vkEnumeratePhysicalDevices"))
		return false;
	if (count == 0)
	{
		nlwarning("Vulkan: no physical device");
		return false;
	}
	vector<VkPhysicalDevice> devices(count);
	vkEnumeratePhysicalDevices(_Instance, &count, &devices[0]);

	for (uint i = 0; i < devices.size(); ++i)
	{
		VkPhysicalDeviceProperties props;
		vkGetPhysicalDeviceProperties(devices[i], &props);
		if (props.apiVersion < VK_API_VERSION_1_1)
			continue;

		uint32 qcount = 0;
		vkGetPhysicalDeviceQueueFamilyProperties(devices[i], &qcount, NULL);
		vector<VkQueueFamilyProperties> queues(qcount);
		vkGetPhysicalDeviceQueueFamilyProperties(devices[i], &qcount, &queues[0]);
		for (uint q = 0; q < queues.size(); ++q)
		{
			if (!(queues[q].queueFlags & VK_QUEUE_GRAPHICS_BIT))
				continue;
			VkBool32 present = VK_FALSE;
			vkGetPhysicalDeviceSurfaceSupportKHR(devices[i], q, _Surface, &present);
			if (!present)
				continue;

			_PhysicalDevice = devices[i];
			_GraphicsFamily = q;
			_DeviceProps = props;
			VkPhysicalDeviceFeatures features;
			vkGetPhysicalDeviceFeatures(devices[i], &features);
			_SupportsBC = (features.textureCompressionBC == VK_TRUE);
			nlinfo("Vulkan: using '%s' (API %u.%u.%u)", props.deviceName,
				VK_VERSION_MAJOR(props.apiVersion), VK_VERSION_MINOR(props.apiVersion), VK_VERSION_PATCH(props.apiVersion));
			return true;
		}
	}
	nlwarning("Vulkan: no device with a graphics+present queue");
	return false;
}

/// Sets a fresh descriptor pool of a frame slot can hold. A frame that needs
/// more adds another, larger pool (see allocDescriptorSet()).
static const uint32 NL_VK_DESCRIPTOR_POOL_SETS = 4096;
/// Descriptors one set of either layout can use: the simple layout allocates
/// 1 UBO and 4 samplers, the mega layout 7 UBOs and 8 samplers. Sizing the
/// pool for the larger one lets both layouts share it.
static const uint32 NL_VK_DESCRIPTOR_SET_SAMPLERS = (uint32)NL_VK_MEGA_SAMPLER_COUNT;
static const uint32 NL_VK_DESCRIPTOR_SET_UNIFORMS = 7;

bool CDriverVulkan::createDescriptorPool(uint32 frame, uint32 maxSets)
{
	VkDescriptorPoolSize poolSize[2];
	poolSize[0].type = VK_DESCRIPTOR_TYPE_COMBINED_IMAGE_SAMPLER;
	poolSize[0].descriptorCount = NL_VK_DESCRIPTOR_SET_SAMPLERS * maxSets;
	poolSize[1].type = VK_DESCRIPTOR_TYPE_UNIFORM_BUFFER;
	poolSize[1].descriptorCount = NL_VK_DESCRIPTOR_SET_UNIFORMS * maxSets;
	VkDescriptorPoolCreateInfo dpci;
	memset(&dpci, 0, sizeof(dpci));
	dpci.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO;
	dpci.maxSets = maxSets;
	dpci.poolSizeCount = 2;
	dpci.pPoolSizes = poolSize;
	VkDescriptorPool pool = VK_NULL_HANDLE;
	if (!checkVk(vkCreateDescriptorPool(_Device, &dpci, NULL, &pool), "vkCreateDescriptorPool"))
		return false;
	_DescriptorPools[frame].push_back(pool);
	return true;
}

VkDescriptorSet CDriverVulkan::allocDescriptorSet(VkDescriptorSetLayout layout)
{
	const uint32 frame = _FrameIndex;
	if (_DescriptorPools[frame].empty() && !createDescriptorPool(frame, NL_VK_DESCRIPTOR_POOL_SETS))
		return VK_NULL_HANDLE;

	VkDescriptorSetAllocateInfo dsai;
	memset(&dsai, 0, sizeof(dsai));
	dsai.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO;
	dsai.descriptorPool = _DescriptorPools[frame].back();
	dsai.descriptorSetCount = 1;
	dsai.pSetLayouts = &layout;

	VkDescriptorSet set = VK_NULL_HANDLE;
	VkResult result = vkAllocateDescriptorSets(_Device, &dsai, &set);
	if (result == VK_ERROR_OUT_OF_POOL_MEMORY || result == VK_ERROR_FRAGMENTED_POOL)
	{
		// This frame has more draws than the pool holds. Add a larger pool to
		// the slot and retry; the pools are reset (not recreated) when the
		// slot is reused, so a dense frame only pays for this once. The new
		// pool doubles the previous capacity, up to 131072 sets, so the list
		// stays short even for a frame with a hundred thousand draws.
		const uint32 shift = std::min<size_t>(_DescriptorPools[frame].size(), 5);
		const uint32 maxSets = NL_VK_DESCRIPTOR_POOL_SETS << shift;
		if (!createDescriptorPool(frame, maxSets))
			return VK_NULL_HANDLE;
		dsai.descriptorPool = _DescriptorPools[frame].back();
		result = vkAllocateDescriptorSets(_Device, &dsai, &set);
		if (result == VK_SUCCESS)
			nlinfo("Vulkan: descriptor pool for frame slot %u grown to %u sets", frame, maxSets);
	}
	if (result != VK_SUCCESS)
	{
		nlwarning("Vulkan: vkAllocateDescriptorSets failed (%d %s)", (int)result, vkResultName(result));
		return VK_NULL_HANDLE;
	}
	return set;
}

bool CDriverVulkan::createLogicalDevice()
{
	float priority = 1.f;
	VkDeviceQueueCreateInfo qci;
	memset(&qci, 0, sizeof(qci));
	qci.sType = VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO;
	qci.queueFamilyIndex = _GraphicsFamily;
	qci.queueCount = 1;
	qci.pQueuePriorities = &priority;

	const char *extensions[] = { VK_KHR_SWAPCHAIN_EXTENSION_NAME };

	VkPhysicalDeviceFeatures supported;
	vkGetPhysicalDeviceFeatures(_PhysicalDevice, &supported);

	VkPhysicalDeviceFeatures features;
	memset(&features, 0, sizeof(features));
	features.fillModeNonSolid = VK_TRUE; // wireframe polygon mode
	features.wideLines = VK_TRUE;
	// Needed to upload DXTC textures without expanding them on the CPU.
	features.textureCompressionBC = _SupportsBC ? VK_TRUE : VK_FALSE;
	// Exact sample counts for the flare visibility ratio. Optional: without
	// it an occlusion query may return 0/1 and the flare pops instead of
	// fading, which is what GLES does as well.
	features.occlusionQueryPrecise = supported.occlusionQueryPrecise;
	_OcclusionPrecise = supported.occlusionQueryPrecise == VK_TRUE;
	// Water reflection passes clip the mirrored scene with user clip planes:
	// the vertex shaders write gl_ClipDistance, which needs this core feature.
	features.shaderClipDistance = supported.shaderClipDistance;
	_ShaderClipDistance = supported.shaderClipDistance == VK_TRUE;
	if (!_ShaderClipDistance)
		nlwarning("Vulkan: shaderClipDistance is not supported; realtime planar water reflections stay disabled");

	VkDeviceCreateInfo dci;
	memset(&dci, 0, sizeof(dci));
	dci.sType = VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO;
	dci.queueCreateInfoCount = 1;
	dci.pQueueCreateInfos = &qci;
	dci.enabledExtensionCount = 1;
	dci.ppEnabledExtensionNames = extensions;
	dci.pEnabledFeatures = &features;

	if (!checkVk(vkCreateDevice(_PhysicalDevice, &dci, NULL, &_Device), "vkCreateDevice"))
		return false;
	vkGetDeviceQueue(_Device, _GraphicsFamily, 0, &_GraphicsQueue);
	return true;
}

