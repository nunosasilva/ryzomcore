bool CDriverVulkan::isActive()
{
	if (!_Display || !_XWindow)
		return false;
	XWindowAttributes attributes;
	if (!XGetWindowAttributes(_Display, _XWindow, &attributes))
		return false;
	if (attributes.width != (int)_WindowWidth || attributes.height != (int)_WindowHeight)
	{
		// The swapchain is recreated lazily by beginFrame().
		_WindowWidth = attributes.width;
		_WindowHeight = attributes.height;
	}
	return attributes.map_state != IsUnmapped;
}

// ---------------------------------------------------------------------------
// Frame loop
// ---------------------------------------------------------------------------

bool CDriverVulkan::beginFrame()
{
	if (_FrameOpen)
		return true;
	if (!_Device)
		return false;

	uint32 frame = _FrameIndex;
	vkWaitForFences(_Device, 1, &_Fences[frame], VK_TRUE, UINT64_MAX);

	// Everything recorded for this frame slot is finished; safe to reset the
	// per-draw descriptor sets and release unused textures.
	vkResetDescriptorPool(_Device, _DescriptorPools[frame], 0);
	if (!_PendingTextureDestroy.empty() || !_PendingBufferDestroy.empty())
		vkDeviceWaitIdle(_Device);
	for (uint i = 0; i < _PendingTextureDestroy.size(); ++i)
	{
		CTextureVulkan tex = _PendingTextureDestroy[i];
		if (tex.Sampler) vkDestroySampler(_Device, tex.Sampler, NULL);
		if (tex.View) vkDestroyImageView(_Device, tex.View, NULL);
		if (tex.Image) vkDestroyImage(_Device, tex.Image, NULL);
		if (tex.Memory) vkFreeMemory(_Device, tex.Memory, NULL);
	}
	_PendingTextureDestroy.clear();
	for (uint i = 0; i < _PendingBufferDestroy.size(); ++i)
	{
		vkDestroyBuffer(_Device, _PendingBufferDestroy[i].first, NULL);
		vkFreeMemory(_Device, _PendingBufferDestroy[i].second, NULL);
	}
	_PendingBufferDestroy.clear();

	VkResult acquire = vkAcquireNextImageKHR(_Device, _Swapchain, UINT64_MAX,
		_ImageAvailable[frame], VK_NULL_HANDLE, &_ImageIndex);
	if (acquire == VK_ERROR_OUT_OF_DATE_KHR)
	{
		recreateSwapchain();
		return false;
	}
	if (acquire != VK_SUCCESS && acquire != VK_SUBOPTIMAL_KHR)
	{
		nlwarning("Vulkan: vkAcquireNextImageKHR failed (%d)", (int)acquire);
		return false;
	}
	vkResetFences(_Device, 1, &_Fences[frame]);

	VkCommandBuffer cmd = _CommandBuffers[frame];
	vkResetCommandBuffer(cmd, 0);
	VkCommandBufferBeginInfo bi;
	memset(&bi, 0, sizeof(bi));
	bi.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
	bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
	if (!checkVk(vkBeginCommandBuffer(cmd, &bi), "vkBeginCommandBuffer"))
		return false;

	VkClearValue clears[2];
	memset(clears, 0, sizeof(clears));
	if (getenv("NLVK_FORCECLEAR"))
	{
		clears[0].color.float32[0] = 1.f;
		clears[0].color.float32[1] = 0.f;
		clears[0].color.float32[2] = 1.f;
		clears[0].color.float32[3] = 1.f;
	}
	else
	{
		clears[0].color.float32[0] = _ClearColor.R / 255.f;
		clears[0].color.float32[1] = _ClearColor.G / 255.f;
		clears[0].color.float32[2] = _ClearColor.B / 255.f;
		clears[0].color.float32[3] = _ClearColor.A / 255.f;
	}
	clears[1].depthStencil.depth = _ClearDepth;
	clears[1].depthStencil.stencil = (uint32)_ClearStencil;

	VkRenderPassBeginInfo rbi;
	memset(&rbi, 0, sizeof(rbi));
	rbi.sType = VK_STRUCTURE_TYPE_RENDER_PASS_BEGIN_INFO;
	rbi.renderPass = _RenderPass;
	rbi.framebuffer = _Framebuffers[_ImageIndex];
	rbi.renderArea.offset.x = 0;
	rbi.renderArea.offset.y = 0;
	rbi.renderArea.extent = _SwapchainExtent;
	rbi.clearValueCount = 2;
	rbi.pClearValues = clears;
	vkCmdBeginRenderPass(cmd, &rbi, VK_SUBPASS_CONTENTS_INLINE);

	// Apply the cached viewport and scissor (they may have been set before the
	// frame was opened; defaults are full screen).
	{
		float x = _Viewport.getX() * _SwapchainExtent.width;
		float y = _Viewport.getY() * _SwapchainExtent.height;
		float w = _Viewport.getWidth() * _SwapchainExtent.width;
		float h = _Viewport.getHeight() * _SwapchainExtent.height;
		VkViewport vkViewport;
		vkViewport.x = x;
		vkViewport.y = (float)_SwapchainExtent.height - y;
		vkViewport.width = w > 0.f ? w : (float)_SwapchainExtent.width;
		vkViewport.height = h > 0.f ? -h : -(float)_SwapchainExtent.height;
		vkViewport.minDepth = 0.f;
		vkViewport.maxDepth = 1.f;
		vkCmdSetViewport(cmd, 0, 1, &vkViewport);

		VkRect2D scissorRect;
		scissorRect.offset.x = (sint32)(_Scissor.X * _SwapchainExtent.width);
		scissorRect.offset.y = (sint32)(_SwapchainExtent.height - (_Scissor.Y + _Scissor.Height) * _SwapchainExtent.height);
		scissorRect.extent.width = (uint32)(_Scissor.Width * _SwapchainExtent.width);
		scissorRect.extent.height = (uint32)(_Scissor.Height * _SwapchainExtent.height);
		if (scissorRect.extent.width == 0 || scissorRect.extent.height == 0)
		{
			scissorRect.offset.x = 0;
			scissorRect.offset.y = 0;
			scissorRect.extent = _SwapchainExtent;
		}
		vkCmdSetScissor(cmd, 0, 1, &scissorRect);
	}

	_FrameOpen = true;
	_IndexRingOffset = 0;
	_UniformRingOffset = 0;
	_MegaLightTableStaged = false;
	if (_SwapBufferCounter == 0)
	{
		const char *dumpFrame = getenv("NLVK_SCREENSHOT_FRAME");
		_ScreenshotFrame = dumpFrame ? atoi(dumpFrame) : 120;
	}

	if (getenv("NLVK_TESTTRI"))
		drawTestTriangle(cmd);
	return true;
}

bool CDriverVulkan::clear2D(CRGBA rgba)
{
	_ClearColor = rgba;
	_ClearColorPending = true;
	if (_FrameOpen)
	{
		// The pass has already started (the first clear of the frame sets it up).
		VkClearAttachment attachment;
		memset(&attachment, 0, sizeof(attachment));
		attachment.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
		attachment.colorAttachment = 0;
		attachment.clearValue.color.float32[0] = rgba.R / 255.f;
		attachment.clearValue.color.float32[1] = rgba.G / 255.f;
		attachment.clearValue.color.float32[2] = rgba.B / 255.f;
		attachment.clearValue.color.float32[3] = rgba.A / 255.f;
		VkClearRect rect;
		memset(&rect, 0, sizeof(rect));
		rect.rect.extent = _SwapchainExtent;
		rect.layerCount = 1;
		vkCmdClearAttachments(_CommandBuffers[_FrameIndex], 1, &attachment, 1, &rect);
		return true;
	}
	beginFrame();
	return true;
}

bool CDriverVulkan::clearZBuffer(float zval)
{
	_ClearDepth = zval;
	_ClearDepthPending = true;
	if (_FrameOpen)
	{
		VkClearAttachment attachment;
		memset(&attachment, 0, sizeof(attachment));
		attachment.aspectMask = VK_IMAGE_ASPECT_DEPTH_BIT;
		attachment.clearValue.depthStencil.depth = zval;
		VkClearRect rect;
		memset(&rect, 0, sizeof(rect));
		rect.rect.extent = _SwapchainExtent;
		rect.layerCount = 1;
		vkCmdClearAttachments(_CommandBuffers[_FrameIndex], 1, &attachment, 1, &rect);
	}
	return true;
}

bool CDriverVulkan::clearStencilBuffer(sint stencilval)
{
	_ClearStencil = stencilval;
	_ClearStencilPending = true;
	return true;
}

bool CDriverVulkan::clearDepthStencil(float zval, sint stencilval)
{
	return clearZBuffer(zval) && clearStencilBuffer(stencilval);
}

bool CDriverVulkan::swapBuffers()
{
	if (!_Device)
		return false;

	// Resize if the window changed.
	if (_WindowWidth && _WindowHeight &&
		(_WindowWidth != _SwapchainExtent.width || _WindowHeight != _SwapchainExtent.height) &&
		_SwapchainExtent.width != 0)
	{
		recreateSwapchain();
	}

	if (!_FrameOpen && !beginFrame())
		return false;

	uint32 frame = _FrameIndex;
	VkCommandBuffer cmd = _CommandBuffers[frame];

	vkCmdEndRenderPass(cmd);

	bool wantScreenshot = false;
	const char *screenshotPath = getenv("NLVK_SCREENSHOT");
	if (screenshotPath)
	{
		if (getenv("NLVK_SCREENSHOT_SEQ"))
			wantScreenshot = _SwapBufferCounter >= (uint64)_ScreenshotFrame && (_SwapBufferCounter % 600) == 0;
		else
			wantScreenshot = _SwapBufferCounter == (uint64)_ScreenshotFrame;
	}
	if (wantScreenshot)
		recordScreenshotCopy(cmd);

	if (!checkVk(vkEndCommandBuffer(cmd), "vkEndCommandBuffer"))
		return false;

	VkPipelineStageFlags waitStage = VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT;
	VkSubmitInfo si;
	memset(&si, 0, sizeof(si));
	si.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
	si.waitSemaphoreCount = 1;
	si.pWaitSemaphores = &_ImageAvailable[frame];
	si.pWaitDstStageMask = &waitStage;
	si.commandBufferCount = 1;
	si.pCommandBuffers = &cmd;
	si.signalSemaphoreCount = 1;
	si.pSignalSemaphores = &_RenderFinished[_ImageIndex];
	if (!checkVk(vkQueueSubmit(_GraphicsQueue, 1, &si, _Fences[frame]), "vkQueueSubmit"))
		return false;

	if (wantScreenshot)
	{
		vkWaitForFences(_Device, 1, &_Fences[frame], VK_TRUE, UINT64_MAX);
		if (getenv("NLVK_SCREENSHOT_SEQ"))
		{
			char path[512];
			snprintf(path, sizeof(path), "%s.%llu.ppm", screenshotPath, (unsigned long long)_SwapBufferCounter);
			writeScreenshot(path);
		}
		else
		{
			writeScreenshot(screenshotPath);
		}
	}

	VkPresentInfoKHR pi;
	memset(&pi, 0, sizeof(pi));
	pi.sType = VK_STRUCTURE_TYPE_PRESENT_INFO_KHR;
	pi.waitSemaphoreCount = 1;
	pi.pWaitSemaphores = &_RenderFinished[_ImageIndex];
	pi.swapchainCount = 1;
	pi.pSwapchains = &_Swapchain;
	pi.pImageIndices = &_ImageIndex;
	VkResult present = vkQueuePresentKHR(_GraphicsQueue, &pi);
	if (present == VK_ERROR_OUT_OF_DATE_KHR || present == VK_SUBOPTIMAL_KHR)
		recreateSwapchain();
	else if (present != VK_SUCCESS)
		nlwarning("Vulkan: vkQueuePresentKHR failed (%d)", (int)present);

	_FrameIndex = (frame + 1) % 2;
	++_SwapBufferCounter;

	_ClearColorPending = false;
	_ClearDepthPending = false;
	_ClearStencilPending = false;
	_FrameOpen = false;

	if ((_SwapBufferCounter % 600) == 0)
		nldebug("Vulkan: frame %llu, %u vertex draws, %u indexed draws, %u pipelines",
			(unsigned long long)_SwapBufferCounter, _ArrayDrawCount, _IndexedDrawCount,
			(uint)_PipelineCache.size());

	return true;
}

void CDriverVulkan::recordScreenshotCopy(VkCommandBuffer cmd)
{
	VkDeviceSize size = (VkDeviceSize)_SwapchainExtent.width * _SwapchainExtent.height * 4;
	if (_ScreenshotBuffer == VK_NULL_HANDLE || _ScreenshotSize < size)
	{
		if (_ScreenshotBuffer)
		{
			vkDestroyBuffer(_Device, _ScreenshotBuffer, NULL);
			vkFreeMemory(_Device, _ScreenshotMemory, NULL);
		}
		VkBufferCreateInfo bci;
		memset(&bci, 0, sizeof(bci));
		bci.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
		bci.size = size;
		bci.usage = VK_BUFFER_USAGE_TRANSFER_DST_BIT;
		bci.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
		if (vkCreateBuffer(_Device, &bci, NULL, &_ScreenshotBuffer) != VK_SUCCESS)
			return;
		VkMemoryRequirements req;
		vkGetBufferMemoryRequirements(_Device, _ScreenshotBuffer, &req);
		VkMemoryAllocateInfo mai;
		memset(&mai, 0, sizeof(mai));
		mai.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
		mai.allocationSize = req.size;
		mai.memoryTypeIndex = findMemoryType(req.memoryTypeBits,
			VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
		if (vkAllocateMemory(_Device, &mai, NULL, &_ScreenshotMemory) != VK_SUCCESS)
			return;
		vkBindBufferMemory(_Device, _ScreenshotBuffer, _ScreenshotMemory, 0);
		vkMapMemory(_Device, _ScreenshotMemory, 0, VK_WHOLE_SIZE, 0, &_ScreenshotMapped);
		_ScreenshotSize = size;
	}

	// The image is in PRESENT_SRC layout at the end of the render pass.
	VkImageMemoryBarrier barrier;
	memset(&barrier, 0, sizeof(barrier));
	barrier.sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER;
	barrier.oldLayout = VK_IMAGE_LAYOUT_PRESENT_SRC_KHR;
	barrier.newLayout = VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL;
	barrier.srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
	barrier.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
	barrier.image = _SwapchainImages[_ImageIndex];
	barrier.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
	barrier.subresourceRange.levelCount = 1;
	barrier.subresourceRange.layerCount = 1;
	barrier.srcAccessMask = VK_ACCESS_COLOR_ATTACHMENT_WRITE_BIT;
	barrier.dstAccessMask = VK_ACCESS_TRANSFER_READ_BIT;
	vkCmdPipelineBarrier(cmd, VK_PIPELINE_STAGE_COLOR_ATTACHMENT_OUTPUT_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT, 0, 0, NULL, 0, NULL, 1, &barrier);
	VkBufferImageCopy region;
	memset(&region, 0, sizeof(region));
	region.imageSubresource.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
	region.imageSubresource.layerCount = 1;
	region.imageExtent.width = _SwapchainExtent.width;
	region.imageExtent.height = _SwapchainExtent.height;
	region.imageExtent.depth = 1;
	vkCmdCopyImageToBuffer(cmd, _SwapchainImages[_ImageIndex], VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, _ScreenshotBuffer, 1, &region);
	barrier.oldLayout = VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL;
	barrier.newLayout = VK_IMAGE_LAYOUT_PRESENT_SRC_KHR;
	barrier.srcAccessMask = VK_ACCESS_TRANSFER_READ_BIT;
	barrier.dstAccessMask = 0;
	vkCmdPipelineBarrier(cmd, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT, 0, 0, NULL, 0, NULL, 1, &barrier);
}

void CDriverVulkan::writeScreenshot(const char *path)
{
	if (!_ScreenshotMapped)
		return;
	FILE *fp = fopen(path, "wb");
	if (!fp)
		return;
	fprintf(fp, "P6\n%u %u\n255\n", _SwapchainExtent.width, _SwapchainExtent.height);
	const uint8 *src = (const uint8 *)_ScreenshotMapped;
	vector<uint8> row(_SwapchainExtent.width * 3);
	for (uint32 y = 0; y < _SwapchainExtent.height; ++y)
	{
		const uint8 *line = src + (VkDeviceSize)y * _SwapchainExtent.width * 4;
		for (uint32 x = 0; x < _SwapchainExtent.width; ++x)
		{
			row[x * 3 + 0] = line[x * 4 + 2];
			row[x * 3 + 1] = line[x * 4 + 1];
			row[x * 3 + 2] = line[x * 4 + 0];
		}
		fwrite(&row[0], 1, row.size(), fp);
	}
	fclose(fp);
	nlinfo("Vulkan: screenshot written to '%s'", path);
}

void CDriverVulkan::getBuffer(CBitmap &bitmap)
{
	if (!_Device || _SwapchainImages.empty())
	{
		bitmap.resize(0, 0);
		return;
	}

	// Best-effort readback of the last presented image. Copying inside a frame
	// (recordScreenshotCopy) is the well-defined path; this is used by the
	// client's screenshot command outside the frame.
	vkDeviceWaitIdle(_Device);

	VkDeviceSize size = (VkDeviceSize)_SwapchainExtent.width * _SwapchainExtent.height * 4;
	VkBufferCreateInfo bci;
	memset(&bci, 0, sizeof(bci));
	bci.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
	bci.size = size;
	bci.usage = VK_BUFFER_USAGE_TRANSFER_DST_BIT;
	bci.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
	VkBuffer buffer = VK_NULL_HANDLE;
	if (vkCreateBuffer(_Device, &bci, NULL, &buffer) != VK_SUCCESS)
		return;
	VkMemoryRequirements req;
	vkGetBufferMemoryRequirements(_Device, buffer, &req);
	VkMemoryAllocateInfo mai;
	memset(&mai, 0, sizeof(mai));
	mai.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
	mai.allocationSize = req.size;
	mai.memoryTypeIndex = findMemoryType(req.memoryTypeBits,
		VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
	VkDeviceMemory memory = VK_NULL_HANDLE;
	if (vkAllocateMemory(_Device, &mai, NULL, &memory) != VK_SUCCESS)
	{
		vkDestroyBuffer(_Device, buffer, NULL);
		return;
	}
	vkBindBufferMemory(_Device, buffer, memory, 0);

	VkCommandBuffer cmd = VK_NULL_HANDLE;
	VkCommandBufferAllocateInfo cbi;
	memset(&cbi, 0, sizeof(cbi));
	cbi.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO;
	cbi.commandPool = _CommandPool;
	cbi.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
	cbi.commandBufferCount = 1;
	vkAllocateCommandBuffers(_Device, &cbi, &cmd);
	VkCommandBufferBeginInfo bi;
	memset(&bi, 0, sizeof(bi));
	bi.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO;
	bi.flags = VK_COMMAND_BUFFER_USAGE_ONE_TIME_SUBMIT_BIT;
	vkBeginCommandBuffer(cmd, &bi);

	VkImageMemoryBarrier barrier;
	memset(&barrier, 0, sizeof(barrier));
	barrier.sType = VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER;
	barrier.oldLayout = VK_IMAGE_LAYOUT_PRESENT_SRC_KHR;
	barrier.newLayout = VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL;
	barrier.srcQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
	barrier.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
	barrier.image = _SwapchainImages[_ImageIndex];
	barrier.subresourceRange.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
	barrier.subresourceRange.levelCount = 1;
	barrier.subresourceRange.layerCount = 1;
	barrier.dstAccessMask = VK_ACCESS_TRANSFER_READ_BIT;
	vkCmdPipelineBarrier(cmd, VK_PIPELINE_STAGE_ALL_COMMANDS_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT, 0, 0, NULL, 0, NULL, 1, &barrier);

	VkBufferImageCopy region;
	memset(&region, 0, sizeof(region));
	region.imageSubresource.aspectMask = VK_IMAGE_ASPECT_COLOR_BIT;
	region.imageSubresource.layerCount = 1;
	region.imageExtent.width = _SwapchainExtent.width;
	region.imageExtent.height = _SwapchainExtent.height;
	region.imageExtent.depth = 1;
	vkCmdCopyImageToBuffer(cmd, _SwapchainImages[_ImageIndex], VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, buffer, 1, &region);

	barrier.oldLayout = VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL;
	barrier.newLayout = VK_IMAGE_LAYOUT_PRESENT_SRC_KHR;
	barrier.srcAccessMask = VK_ACCESS_TRANSFER_READ_BIT;
	barrier.dstAccessMask = 0;
	vkCmdPipelineBarrier(cmd, VK_PIPELINE_STAGE_TRANSFER_BIT, VK_PIPELINE_STAGE_ALL_COMMANDS_BIT, 0, 0, NULL, 0, NULL, 1, &barrier);
	vkEndCommandBuffer(cmd);

	VkSubmitInfo si;
	memset(&si, 0, sizeof(si));
	si.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO;
	si.commandBufferCount = 1;
	si.pCommandBuffers = &cmd;
	vkQueueSubmit(_GraphicsQueue, 1, &si, VK_NULL_HANDLE);
	vkQueueWaitIdle(_GraphicsQueue);

	void *mapped = NULL;
	vkMapMemory(_Device, memory, 0, VK_WHOLE_SIZE, 0, &mapped);
	bitmap.resize(_SwapchainExtent.width, _SwapchainExtent.height, CBitmap::RGBA);
	uint8 *dst = (uint8 *)bitmap.getPixels(0).getPtr();
	const uint8 *src = (const uint8 *)mapped;
	for (uint32 i = 0; i < _SwapchainExtent.width * _SwapchainExtent.height; ++i)
	{
		dst[i * 4 + 0] = src[i * 4 + 2]; // B -> R
		dst[i * 4 + 1] = src[i * 4 + 1];
		dst[i * 4 + 2] = src[i * 4 + 0]; // R -> B
		dst[i * 4 + 3] = src[i * 4 + 3];
	}
	vkUnmapMemory(_Device, memory);

	vkFreeCommandBuffers(_Device, _CommandPool, 1, &cmd);
	vkDestroyBuffer(_Device, buffer, NULL);
	vkFreeMemory(_Device, memory, NULL);
}

