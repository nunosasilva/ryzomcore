/**
 * Native Vulkan 3D driver for NeL.
 *
 * This is a from-scratch implementation of IDriver. It intentionally follows
 * the structure of the OpenGL3 driver (same shader model: GLSL generated by
 * the engine, uniform buffers for camera/object/material/light state), but the
 * backend is Vulkan instead of OpenGL.
 *
 * Status: work in progress. The window, swapchain, frame loop and clears are
 * implemented; the draw path is being filled in subsystem by subsystem.
 */

