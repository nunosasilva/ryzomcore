#ifndef NL_VEGETABLE_EXTRA_H
#define NL_VEGETABLE_EXTRA_H

#include "nel/misc/types_nl.h"
#include "nel/3d/vegetable_def.h"

#include <vector>


namespace NL3D
{


class CTileVegetableDesc;
class CVegetable;


// ***************************************************************************
/**
 * Opt-in extension of the microvegetation distance (client.cfg MicroVegetExtra).
 *
 * The stock landscape has five authored species sets over 0..50m (10m each).
 * When this strategy is enabled, the same five sets cover 0..100m (20m each),
 * the far ZSort layers are stretched to match, and the farthest bucket also
 * copies the lower buckets' species so that a band edge never swaps the plants
 * under the camera. The copies reuse the lower band's own seed and own scale,
 * so they are exact duplicates of a subset of that band's instances; only the
 * density changes (one small thinning per band edge instead of a species
 * swap). Tilesets whose lower bands are empty (desert floor/canyon) keep the
 * authored far density.
 *
 * When disabled, nothing here is used: the stock 0..50m LUT, the authored
 * lists and the authored densities/scales are generated by the regular path.
 */
class CVegetableExtra
{
public:
	/// One species list to generate into a tile's instance group.
	struct CSource
	{
		const CVegetable	*Veget;
		uint32				Seed;
		/// Multiplier on the authored instance count (1 = authored).
		float				Density;
		/// Multiplier on the authored instance scale (1 = authored).
		float				Scale;
	};

	CVegetableExtra();

	/// Master switch. Set before the first vegetable block is created.
	void					setEnabled(bool enabled) { _Enabled = enabled; }
	bool					isEnabled() const { return _Enabled; }

	/// Number of distance buckets (the .vegetset file format keeps five).
	static uint				getNumBands() { return NL3D_VEGETABLE_BLOCK_NUMDIST; }
	/// Width of one band in the extended mode, in metres.
	static float			getBandDist() { return 20.f; }
	/// Far edge of a bucket in the extended mode (20,40,60,80,100).
	static float			getBandFarDist(uint distType);

	/// Squared bucket edges used by the block distance state machine.
	/// Index 0..NUMDIST; the last entry is the far edge (100m).
	const float				*getSqrDistLUT() const { return _SqrDistLUT; }

	/// Distance where the instances of a bucket reach alpha 0 in the extended
	/// mode. The fade starts at getBlendDistMax() - getBlendTransitionDist().
	float					getBlendDistMax(uint distType) const { return getBandFarDist(distType); }
	/// Width of the alpha fade at a band edge (stock 10m transition).
	static float			getBlendTransitionDist() { return NL3D_VEGETABLE_BLOCK_BLEND_TRANSITION_DIST; }

	/// Distance of the farthest ZSort blend layer needed by the extended mode.
	/// It covers the 100m far edge plus one 20m band of margin. The alpha fade
	/// itself is the 10m blend transition at the far edge
	/// (getBlendTransitionDist()); the extra margin keeps the farthest sort
	/// blocks out of the last-layer clamp instead of piling them on layer 19.
	static float			getZSortDistMax() { return 120.f; }

	/// Density of the lower-band copies in the farthest carrier (P2 knob).
	static float			getUnionDensity() { return 0.26f; }
	/// Far bucket density when every lower band is empty (desert/canyon).
	static float			getFarOnlyDensity() { return 1.f; }

	/// Density/scale multiplier of the bucket's own authored list. Exposed so
	/// the verification log can report the actual far-only value (1.0).
	float					getOwnDensity(const CTileVegetableDesc &tileVegetDesc, uint distType) const;
	float					getOwnScale(uint distType) const;

	/** Build the lists generated by one tile's carrier bucket in extended mode:
	 *	the bucket's own authored list at the band density/scale, then (in the
	 *	farthest bucket only) every lower list at the union density, with that
	 *	lower band's seed and scale.
	 */
	void					buildSources(const CTileVegetableDesc &tileVegetDesc, uint distType,
								std::vector<CSource> &sources) const;

private:
	bool					_Enabled;
	/// getBandFarDist(i)^2, monotonically increasing.
	float					_SqrDistLUT[NL3D_VEGETABLE_BLOCK_NUMDIST + 1];
};


} // NL3D


#endif // NL_VEGETABLE_EXTRA_H

